
import json
import re
import requests

from datetime import datetime, timedelta
from zoneinfo import ZoneInfo

from pydantic import ValidationError

from .schemas import PlanProposal, ProposedJob
from .registry import AGENTS


OLLAMA_URL = "http://127.0.0.1:11434/api/generate"
MODEL_NAME = "qwen3:8b"

USER_TIMEZONE = "Asia/Ho_Chi_Minh"
TZ = ZoneInfo(USER_TIMEZONE)


SYSTEM_PROMPT = r'''
You are the planning brain of a multi-agent task orchestration system.

Your ONLY job is to turn the user's request into a proposed plan.
Never execute tools or claim that a task has been completed.

Only assign jobs to supplied registered agents and their capabilities.

Return valid JSON only, with these keys:
{
  "title": "short title",
  "summary": "plain-language plan summary",
  "needs_clarification": false,
  "clarification_questions": [],
  "jobs": [
    {
      "job_key": "step_1",
      "job_type": "registered capability",
      "target_agent": "registered agent",
      "description": "what it should do",
      "payload": {},
      "schedule": {},
      "depends_on": []
    }
  ]
}

Rules:
- For a simple reminder, use reminder_agent with job_type create_reminder.
- For reminder_agent/create_reminder:
  - payload MUST contain a short "title" and an optional "description".
  - schedule MUST use type "once" and contain a timezone-aware ISO-8601 datetime.
  - Do not put the scheduled datetime in payload; put it in schedule.datetime.
- IMPORTANT: target_agent and job_type are separate fields.
- job_type MUST contain only the exact capability name from the
  registered agent's capabilities list. NEVER include the agent name
  or a slash in job_type.
- For research, summarization, then email, use:
  research_agent with job_type "web_research",
  summarization_agent with job_type "summarize",
  email_agent with job_type "send_email".
- IMPORTANT: If the user asks to summarize a PDF/document that has ALREADY
  been uploaded to this chatbot, use chatbot_agent with job_type
  "summarize_document", not summarization_agent.
- For chatbot_agent/summarize_document, payload MUST contain:
  {"source": "the exact uploaded PDF filename including .pdf"}
  Copy the filename exactly as supplied by the user. Do not invent a filename.
  If the user has not identified which saved document to summarize, set
  needs_clarification=true, ask which uploaded PDF they mean, and return no jobs.
- Split multi-step goals into useful jobs and express dependencies.
- Do not invent recipient addresses, credentials, or user preferences.
- If essential information is missing or ambiguous, ask for clarification.
- For one-time schedules use:
  {"type":"once","datetime":"ISO-8601 with UTC offset"}
- For recurring schedules use:
  {"type":"recurring","rrule":"RFC5545 RRULE",
   "time":"HH:MM","timezone":"IANA timezone"}
- User timezone is Asia/Ho_Chi_Minh unless specified otherwise.
- Use the CURRENT DATE AND TIME provided in the prompt.
- Resolve words such as today, tomorrow and next week relative to that date.
- NEVER use dates from your training data or assume the current year.
- Every job is a proposal requiring user approval before execution.
'''.strip()


def _get_current_time():
    """Get authoritative current time in the user's timezone."""
    return datetime.now(TZ)


def _parse_datetime(value):
    """Parse ISO datetime and normalize it to the user timezone."""
    if not value:
        raise ValueError("Missing schedule datetime.")

    try:
        result = datetime.fromisoformat(
            str(value).replace("Z", "+00:00")
        )
    except ValueError as exc:
        raise ValueError(
            f"Invalid ISO datetime returned by planner: {value}"
        ) from exc

    if result.tzinfo is None:
        result = result.replace(tzinfo=TZ)

    return result.astimezone(TZ)


def _expected_relative_date(user_request, now):
    """
    Resolve common relative dates deterministically.
    Returns None when no supported relative-date expression exists.
    """
    text = user_request.lower()

    if re.search(r"\b(day after tomorrow|the day after tomorrow)\b", text):
        return (now + timedelta(days=2)).date()

    if re.search(r"\b(tomorrow|ngày mai|mai)\b", text):
        return (now + timedelta(days=1)).date()

    if re.search(r"\b(today|tonight|hôm nay)\b", text):
        return now.date()

    return None


def _normalize_job_schedule(job, user_request, now):
    """
    Correct relative dates using Python's clock rather than trusting
    dates generated by the LLM.
    """
    schedule = job.schedule

    if not schedule:
        return

    if not isinstance(schedule, dict):
        schedule = schedule.dict()

    if schedule.get("type") != "once":
        return

    scheduled_at = _parse_datetime(schedule.get("datetime"))

    expected_date = _expected_relative_date(user_request, now)

    if expected_date is not None:
        # Preserve the time proposed by the LLM, but use the
        # deterministic date calculated by Python.
        scheduled_at = scheduled_at.replace(
            year=expected_date.year,
            month=expected_date.month,
            day=expected_date.day,
        )

    if scheduled_at <= now:
        raise ValueError(
            f"Job {job.job_key} has a schedule in the past: "
            f"{scheduled_at.isoformat()}. Please regenerate the plan."
        )

    schedule["datetime"] = scheduled_at.isoformat()
    job.schedule = schedule



def _validate_graph(proposal: PlanProposal):
    keys = [job.job_key for job in proposal.jobs]

    if len(keys) != len(set(keys)):
        raise ValueError("Planner returned duplicate job_key values.")

    known = set(keys)
    graph = {}

    for job in proposal.jobs:
        if job.target_agent not in AGENTS:
            raise ValueError(
                f"Unregistered agent: {job.target_agent}"
            )

        capabilities = AGENTS[job.target_agent]["capabilities"]

        # Normalize accidental agent/capability format from the LLM.
        if job.job_type.startswith(f"{job.target_agent}/"):
            job.job_type = job.job_type.split("/", 1)[1]

        if job.job_type not in capabilities:
            raise ValueError(
                f"Capability '{job.job_type}' is not allowed "
                f"for agent '{job.target_agent}'. "
                f"Allowed capabilities: {capabilities}"
            )

        missing = set(job.depends_on) - known

        if missing:
            raise ValueError(
                f"Unknown dependencies for {job.job_key}: "
                f"{sorted(missing)}"
            )

        if job.job_key in job.depends_on:
            raise ValueError("A job cannot depend on itself.")

        graph[job.job_key] = set(job.depends_on)

    # Detect dependency cycles.
    remaining = {
        key: set(deps)
        for key, deps in graph.items()
    }

    while remaining:
        ready = [
            key for key, deps in remaining.items()
            if not deps
        ]

        if not ready:
            raise ValueError(
                "Job dependencies contain a cycle."
            )

        for key in ready:
            remaining.pop(key)

        for deps in remaining.values():
            deps.difference_update(ready)


def _build_saved_pdf_summary_plan(user_request: str):
    """Deterministically route saved-PDF summary requests to chatbot_agent.

    Do not rely on the planning LLM to choose this route: the old planner
    sometimes selected summarization_agent and passed only a filename, which
    cannot work with the text-only summarization handler.
    """
    request_text = user_request.strip()
    lowered = request_text.casefold()
    summary_terms = (
        "summarize", "summarise", "summary", "tóm tắt", "tom tat"
    )
    document_terms = (
        "document", "pdf", "file", "tài liệu", "tai lieu", "doc"
    )
    if not any(term in lowered for term in summary_terms):
        return None
    if not any(term in lowered for term in document_terms):
        return None

    # Match a filename token, not an arbitrary path. Chroma stores the PDF
    # basename in metadata under the `source` key.
    match = re.search(r"(?i)(?<![\w.-])([^\\/\s\"'<>]+\.pdf)(?![\w.-])", request_text)
    if not match:
        return PlanProposal(
            title="Clarify Document to Summarize",
            summary="The uploaded PDF filename is needed before the chatbot can summarize it.",
            needs_clarification=True,
            clarification_questions=["Which uploaded PDF should I summarize? Please provide its exact filename, including .pdf."],
            jobs=[],
        )

    filename = match.group(1)
    return PlanProposal(
        title="Summarize Document",
        summary=f"Use the existing chatbot agent to summarize all indexed chunks from {filename}.",
        needs_clarification=False,
        clarification_questions=[],
        jobs=[
            ProposedJob(
                job_key="step_1",
                job_type="summarize_document",
                target_agent="chatbot_agent",
                description=f"Summarize the uploaded document {filename} using the chatbot knowledge base.",
                payload={"source": filename},
                schedule={},
                depends_on=[],
            )
        ],
    )


def create_plan(user_request: str) -> PlanProposal:
    # Route saved-PDF summarization before calling the LLM. This prevents
    # the model from accidentally selecting the text-only summarization agent.
    saved_pdf_plan = _build_saved_pdf_summary_plan(user_request)
    if saved_pdf_plan is not None:
        return saved_pdf_plan

    now = _get_current_time()

    temporal_context = f"""
AUTHORITATIVE CURRENT TIME:
{now.isoformat()}

CURRENT LOCAL DATE:
{now.strftime("%Y-%m-%d")}

CURRENT LOCAL TIME:
{now.strftime("%H:%M:%S")}

TIMEZONE:
{USER_TIMEZONE}

IMPORTANT:
Calculate relative dates from the authoritative current date above.
For example, tomorrow means:
{(now + timedelta(days=1)).date().isoformat()}

Do not use any other current date.
"""

    prompt = (
        SYSTEM_PROMPT
        + "\n\n"
        + temporal_context
        + "\nREGISTERED AGENTS:\n"
        + json.dumps(AGENTS, ensure_ascii=False)
        + "\n\nUSER REQUEST:\n"
        + user_request
    )

    response = requests.post(
        OLLAMA_URL,
        json={
            "model": MODEL_NAME,
            "prompt": prompt,
            "stream": False,
            "think": False,
            "format": "json",
        },
        timeout=180,
    )

    response.raise_for_status()

    raw = response.json().get("response", "")

    try:
        proposal = PlanProposal.parse_obj(json.loads(raw))

    except (json.JSONDecodeError, ValidationError) as exc:
        raise ValueError(
            f"Qwen returned an invalid task plan: {exc}"
        ) from exc

    if proposal.needs_clarification:
        if proposal.jobs:
            raise ValueError(
                "Planner must not create jobs while clarification is required."
            )

        return proposal

    if not proposal.jobs:
        raise ValueError(
            "Planner returned an empty plan without asking for clarification."
        )

    # Validate graph and agent permissions.
    _validate_graph(proposal)

    # Normalize and validate all one-time schedules.
    for job in proposal.jobs:
        _normalize_job_schedule(
            job,
            user_request,
            now,
        )

    return proposal
